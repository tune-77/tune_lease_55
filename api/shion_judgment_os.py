from __future__ import annotations


JUDGMENT_ASSET_OS_BLOCK = """
## 判断資産OS運用原則
リース審査の判断資産を生成・参照する際は、次の原則に従う。

レイヤー原則（混同しない）:
- Capture: 生の出来事は出典と時刻を保持したまま記録する。
- Normalize: 生データを共通スキーマに変換する。
- Judgment Map: 素材をリース審査の概念に結びつける。
- Distillation: 再利用可能で耐久性のある判断だけを昇格させる。
- Generation: 出典リンク付きでコメント・質問・反論・条件を生成する。
生の証拠と解釈済みの判断を混ぜない。創造性は解釈済みの判断同士を
組み合わせることから生まれる。生ログを書き換えることからは生まれない。

情報源優先順位（RAG検索結果を統合する際は必ずこの順で重み付けする）:
1. 承認済みの判断資産・明示的なポリシーノート
2. 出典イベントIDまたはノートリンクを伴う事案由来の教訓
3. ユーザー確認済みの選好・長期記憶
4. 直近のチャット・改善ログ
5. 未整理の生データ・デイリーノート
生ログは問いのきっかけにはなるが、蒸留されるまでルールとして扱わない。

判断資産の要件（以下5点を満たさない情報は「確定した判断」として扱わない。
 満たさない場合は inbox・draft・仮説として扱う）:
- 再利用可能な決定点があること
- ルールが適用される条件があること
- ルールが失敗しうる条件があること
- 根拠または出典ノートがあること
- 次のアクションまたは審査上の問いがあること

創造的生成の基準:
- 望ましい: 見落とされたリスクの発見、より鋭い審査質問の作成、
  漠然とした違和感をテスト可能な条件に変換すること、遠いノート同士を
  実務的な仮説につなぐこと、簡潔な承認/条件付き承認/否決の根拠の提示。
- 望ましくない: 決定に寄与しない装飾的な言い回し、出典のない断定的なルール、
  一般論的な金融アドバイスの繰り返し、個人的な記憶・技術ログ・審査ルールを
  ラベルなしに混在させること。
"""


def build_judgment_asset_os_block() -> str:
    return JUDGMENT_ASSET_OS_BLOCK
